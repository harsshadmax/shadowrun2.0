"""SIMULATED AGENT. Task: "Add CSV export to the report module."
The agent proposes a package, submits the install to the Shadow-Run gate, and reacts to the verdict.
All steps are logged via `log` (the API writes them to the agent_events table).

Standalone use: `python -m agent.scripted_agent` asks a running API (`shadowrun serve`) to run it and prints the transcript."""
import json
import os
import sys
import time
import urllib.request
from pathlib import Path

TASK = "Add CSV export to the report module."
CANDIDATES = ["report-export-pro", "csvtoolkit"]
AGENT_ID = "scripted-agent"

REPORT_MODULE = '''"""Generated by the SIMULATED AGENT: CSV export for the report module."""
from csvtoolkit import to_csv


def export_report(rows):
    return to_csv(rows)
'''


def run_task(act, log, workdir: Path | None = None) -> dict:
    """act(spec) -> run summary dict (decision, reason, run_id, ...). log(kind, message, run_id=None)."""
    log("PROPOSE", f"Task: {TASK} I will use `{CANDIDATES[0]}` for the CSV export.")
    chosen = None
    for i, spec in enumerate(CANDIDATES):
        if i > 0:
            log("CHOOSE_ALT", f"Using `{spec}` instead.")
        res = act(spec)
        if res["decision"] == "ALLOW":
            chosen = (spec, res)
            break
        log("BLOCKED_NOTICE",
            f"`{spec}` was {res.get('label') or res['decision']} by Shadow-Run: {res['reason']}", res["run_id"])
        if i + 1 >= len(CANDIDATES):
            break
    if not chosen:
        log("CONTINUE", "No candidate package passed the gate; stopping without installing anything.")
        return {"installed": None}
    spec, res = chosen
    out = (workdir or Path("report_module"))
    out.mkdir(parents=True, exist_ok=True)
    (out / "report_export.py").write_text(REPORT_MODULE)
    log("CONTINUE", f"`{spec}` allowed (limited evidence). Wrote {out / 'report_export.py'}; task complete.",
        res["run_id"])
    return {"installed": spec, "file": str(out / "report_export.py")}


def _api(path: str, base: str, token: str, method="GET", body=None):
    req = urllib.request.Request(base + path, method=method, headers={"X-Demo-Token": token,
                                                                       "Content-Type": "application/json"},
                                 data=json.dumps(body).encode() if body is not None else None)
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read())


def main() -> int:
    base = os.environ.get("SHADOWRUN_API", "http://127.0.0.1:8000")
    from shadowrun import config
    token = os.environ.get("SHADOWRUN_DEMO_TOKEN") or (config.DATA / "demo_token").read_text().strip()
    _api("/api/v1/agent/run", base, token, "POST", {})
    seen = 0
    print(f"[SIMULATED AGENT] {TASK}")
    for _ in range(300):
        time.sleep(1)
        for ev in _api(f"/api/v1/agent/events?since_id={seen}", base, token)["events"]:
            seen = ev["id"]
            print(f"  {ev['kind']:<15} {ev['message']}")
            if ev["kind"] == "CONTINUE":
                return 0
    return 1


if __name__ == "__main__":
    sys.exit(main())
